"""Generate the viz configs from ``whitelist.py`` so every consumer sees the same allow-list.

    python3 -m ultron_b2_viz.gen_configs [--check] [--root ros2_ws/src/ultron_b2_viz]

Writes config/domain_bridge_{sim,replay,live}.yaml, config/zenoh_bridge_{orin,laptop}.json5,
rviz/ultron_viz42.rviz and foxglove/<mode>/ultron_{mapping,nav,mission}.json. ``--check`` exits
non-zero when a committed file differs (used by the tests).
"""
import argparse
import json
from pathlib import Path
import re
import sys

from . import whitelist as wl

HEADER = '# GENERATED by ultron_b2_viz.gen_configs from whitelist.py -- do not edit by hand.\n'


def domain_bridge_yaml(mode):
    domain = wl.MODE_DOMAINS[mode]
    lines = [HEADER.rstrip(),
             f'# {mode}: domain {domain} -> viz domain {wl.VIZ_DOMAIN}. Throttled viz topics only; raw lidar/images',
             '# are never listed. Destination names are mode-independent (/ultron/viz/...) so one laptop RViz',
             '# config works for sim, replay and live. QoS is copied from the discovered publisher.']
    if mode == 'live':
        lines.append('# LIVE (domain 0) is UNRUN: only with explicit operator authorization on the robot network.')
    lines += [f'name: ultron_viz_bridge_{mode}', f'from_domain: {domain}', f'to_domain: {wl.VIZ_DOMAIN}', 'topics:']
    for src, typ, dst in wl.bridge_topics(mode):
        lines.append(f'  {src}:')
        lines.append(f'    type: {typ}')
        if dst != src:
            lines.append(f'    remap: {dst}')
    return '\n'.join(lines) + '\n'


def zenoh_config(side):
    allowed = [re.escape(dst) for _, _, dst in wl.bridge_topics('sim')]
    freqs = [f'{re.escape(wl.viz42_name(rel))}={hz}' for rel, hz in sorted(wl.MAX_HZ.items())]
    if side == 'orin':
        allow = {'publishers': allowed, 'subscribers': [], 'service_servers': [], 'service_clients': [],
                 'action_servers': [], 'action_clients': []}
        net = {'mode': 'router', 'listen': {'endpoints': ['tcp/127.0.0.1:7447']}}
        note = ('Orin side (UNRUN: zenoh-bridge-ros2dds not installed in the dev image). Reads domain 42 '
                '(fed by domain_bridge) and serves ONLY the allow-listed publishers. Listens on loopback; the '
                'laptop reaches it through `ssh -L 7447:127.0.0.1:7447 orin`. Binding a LAN/Wi-Fi address needs '
                'user approval.')
    else:
        allow = {'publishers': [], 'subscribers': allowed, 'service_servers': [], 'service_clients': [],
                 'action_servers': [], 'action_clients': []}
        net = {'mode': 'client', 'connect': {'endpoints': ['tcp/127.0.0.1:7447']}}
        note = ('Laptop side (UNRUN). Recreates the allow-listed topics in the laptop\'s local domain 42 for RViz. '
                'Read-only: no publishers/services are routed back to the robot.')
    cfg = {'plugins': {'ros2dds': {'domain': wl.VIZ_DOMAIN, 'ros_localhost_only': True, 'allow': allow,
                                   'pub_max_frequencies': freqs if side == 'orin' else []}},
           **net, 'adminspace': {'permissions': {'read': False, 'write': False}}}
    return '// ' + HEADER[2:] + '// ' + note + '\n' + json.dumps(cfg, indent=2) + '\n'


def _panel_3d(ns, extra_topics, follow='base_link'):
    topics = {f'{ns}/viz/points': {'visible': True, 'colorField': 'z', 'colorMode': 'colormap', 'pointSize': 2},
              f'{ns}/viz/map': {'visible': True}, f'{ns}/map': {'visible': False},
              f'{ns}/sensors/scan': {'visible': True, 'colorMode': 'flat', 'flatColor': '#ff4040ff'},
              f'{ns}/viz/map_cloud': {'visible': False}, f'{ns}/robot_description': {'visible': True}}
    topics.update({t: {'visible': True} for t in extra_topics})
    return {'cameraState': {'distance': 18, 'perspective': True, 'phi': 50, 'thetaOffset': 0,
                            'targetOffset': [0, 0, 0], 'fovy': 45, 'near': 0.5, 'far': 5000},
            'followMode': 'follow-position', 'followTf': follow, 'scene': {}, 'transforms': {},
            'topics': topics, 'layers': {'grid': {'layerId': 'foxglove.Grid', 'visible': True, 'frameId': 'map',
                                                  'size': 40, 'divisions': 40}},
            'publish': {'type': 'point'}, 'imageMode': {}}


def foxglove_layout(mode, kind):
    ns = wl.MODE_NAMESPACES[mode]
    extra = {'mapping': [],
             'nav': [f'{ns}/viz/plan', f'{ns}/viz/global_costmap', f'{ns}/viz/local_costmap'],
             'mission': [f'{ns}/viz/plan', f'{ns}/viz/local_costmap']}[kind]
    raw = {'mapping': [f'{ns}/state/localization', f'{ns}/state/odom'],
           'nav': [f'{ns}/safety/motion_gate', f'{ns}/control/active_source'],
           'mission': [f'{ns}/mission/status', f'{ns}/perception/ladder_candidates']}[kind]
    config = {'3D!main': _panel_3d(ns, extra),
              'Image!cam': {'cameraState': {}, 'imageMode': {'imageTopic': f'{ns}/viz/cam_head/color/image/compressed'}},
              'RawMessages!a': {'topicPath': raw[0], 'diffEnabled': False, 'expansion': 'auto'},
              'RawMessages!b': {'topicPath': raw[1], 'diffEnabled': False, 'expansion': 'auto'}}
    layout = {'first': '3D!main', 'second': {'first': 'Image!cam', 'second': {
        'first': 'RawMessages!a', 'second': 'RawMessages!b', 'direction': 'column'},
        'direction': 'column', 'splitPercentage': 40}, 'direction': 'row', 'splitPercentage': 65}
    if kind == 'mission':
        config['RawMessages!c'] = {'topicPath': f'{ns}/mission/events', 'diffEnabled': False, 'expansion': 'auto'}
        layout['second']['second']['second'] = {'first': 'RawMessages!b', 'second': 'RawMessages!c',
                                                'direction': 'column'}
    doc = {'configById': config, 'globalVariables': {}, 'userNodes': {}, 'playbackConfig': {'speed': 1},
           'layout': layout,
           '_ultron': {'generated_by': 'ultron_b2_viz.gen_configs', 'mode': mode, 'kind': kind,
                       'note': 'Only whitelisted, throttled topics. Ground truth and raw sensors are not served.'}}
    return json.dumps(doc, indent=2, sort_keys=True) + '\n'


def rviz_config():
    v = wl.viz42_name

    def display(cls, name, **kw):
        lines = [f'    - Class: {cls}', f'      Enabled: true', f'      Name: {name}']
        lines += [f'      {k}: {val}' for k, val in kw.items()]
        return lines

    def topic(name, depth=5, durability='Volatile', reliability='Reliable'):
        return ('\n        Depth: %d\n        Durability Policy: %s\n        History Policy: Keep Last\n'
                '        Reliability Policy: %s\n        Value: %s' % (depth, durability, reliability, name))
    displays = []
    displays += display('rviz_default_plugins/Grid', 'Grid', **{'Reference Frame': 'map', 'Plane Cell Count': 40})
    displays += display('rviz_default_plugins/TF', 'TF', **{'Show Names': 'false', 'Marker Scale': 0.5})
    displays += display('rviz_default_plugins/RobotModel', 'RobotModel', **{
        'Description Source': 'Topic', 'Description Topic': topic(v('robot_description'), 1, 'Transient Local')})
    displays += display('rviz_default_plugins/Map', 'Map', **{
        'Topic': topic(v('viz/map'), 1, 'Transient Local'), 'Color Scheme': 'map', 'Alpha': 0.7})
    displays += display('rviz_default_plugins/Map', 'Global costmap', **{
        'Topic': topic(v('viz/global_costmap')), 'Color Scheme': 'costmap', 'Alpha': 0.4})
    displays += display('rviz_default_plugins/Map', 'Local costmap', **{
        'Topic': topic(v('viz/local_costmap')), 'Color Scheme': 'costmap', 'Alpha': 0.4})
    displays += display('rviz_default_plugins/PointCloud2', 'Lidar (viz, voxelized)', **{
        'Topic': topic(v('viz/points'), 2), 'Size (m)': 0.05, 'Style': 'Points', 'Size (Pixels)': 2,
        'Color Transformer': 'AxisColor', 'Axis': 'Z'})
    displays += display('rviz_default_plugins/PointCloud2', '3D map (viz)', **{
        'Topic': topic(v('viz/map_cloud'), 1), 'Style': 'Points', 'Size (Pixels)': 1,
        'Color Transformer': 'AxisColor', 'Axis': 'Z'})
    displays += display('rviz_default_plugins/LaserScan', 'Scan', **{
        'Topic': topic(v('sensors/scan'), 5, 'Volatile', 'Best Effort'), 'Size (m)': 0.05,
        'Color Transformer': 'FlatColor', 'Color': '255; 64; 64'})
    displays += display('rviz_default_plugins/Odometry', 'Odometry', **{
        'Topic': topic(v('state/odom')), 'Keep': 20, 'Shape': '\n        Value: Arrow'})
    displays += display('rviz_default_plugins/Path', 'Plan', **{'Topic': topic(v('viz/plan')), 'Color': '64; 200; 64'})
    displays += display('rviz_default_plugins/Image', 'Head camera (JPEG)', **{
        'Topic': topic(v('viz/cam_head/color/image'), 2)})
    lines = [HEADER.rstrip(), '# Laptop RViz on domain 42 (ROS_DOMAIN_ID=42). Topics come from domain_bridge/zenoh',
             '# with mode-independent names under /ultron/viz. The image uses the compressed transport',
             '# (set Transport Hint to "compressed" if your RViz does not pick it up automatically).',
             'Panels:', '  - Class: rviz_common/Displays', '    Name: Displays',
             '  - Class: rviz_common/Time', '    Name: Time',
             'Visualization Manager:', '  Class: ""', '  Displays:']
    lines += displays
    lines += ['  Enabled: true', '  Global Options:', '    Background Color: 48; 48; 48', '    Fixed Frame: map',
              '    Frame Rate: 15', '  Name: root', '  Tools:', '    - Class: rviz_default_plugins/MoveCamera',
              '    - Class: rviz_default_plugins/Select', '    - Class: rviz_default_plugins/Measure',
              '  Value: true', '  Views:', '    Current:', '      Class: rviz_default_plugins/Orbit',
              '      Distance: 20', '      Focal Point:', '        X: 6', '        Y: 4', '        Z: 0',
              '      Name: Current View', '      Pitch: 0.9', '      Target Frame: map', '      Yaw: -1.6',
              '    Saved: ~', 'Window Geometry:', '  Height: 900', '  Width: 1500']
    return '\n'.join(lines) + '\n'


def outputs():
    files = {}
    for mode in wl.MODE_NAMESPACES:
        files[f'config/domain_bridge_{mode}.yaml'] = domain_bridge_yaml(mode)
        for kind in ('mapping', 'nav', 'mission'):
            files[f'foxglove/{mode}/ultron_{kind}.json'] = foxglove_layout(mode, kind)
    for side in ('orin', 'laptop'):
        files[f'config/zenoh_bridge_{side}.json5'] = zenoh_config(side)
    files['rviz/ultron_viz42.rviz'] = rviz_config()
    return files


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    p.add_argument('--check', action='store_true')
    args = p.parse_args(argv)
    stale = []
    for rel, text in outputs().items():
        path = args.root / rel
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    if stale:
        print('stale generated files: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
